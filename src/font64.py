def glyph(ch):
    rows = G[ch].split()
    assert len(rows) == 7 and all(len(r) == 3 for r in rows), ch
    out = [0]
    for r in rows:
        v = 0
        for k, c in enumerate(r):
            if c == '#':
                v |= 0x80 >> k
        out.append(v)
    return out

def build():
    data = []
    for code in range(32, 128):
        data += glyph(chr(code))
    return data

if __name__ == '__main__':
    data = build()
    lines = ["; 64-column font (generated by font64.py): ASCII 32-127, glyph in the high nibble",
             "FONT64:"]
    for i in range(0, len(data), 16):
        lines.append("    db " + ",".join(str(b) for b in data[i:i + 16]))
    open(os.path.join(HERE, 'font64.asm'), 'w').write("\n".join(lines) + "\n")
    try:
        from PIL import Image
        im = Image.new('RGB', (32 * 4 + 8, 3 * 8 + 8), (0, 0, 0xD7))
        px = im.load()
        for i in range(96):
            gx, gy = 4 + (i % 32) * 4, 4 + (i // 32) * 8
            for y in range(8):
                for x in range(4):
                    if data[i * 8 + y] & (0x80 >> x):
                        px[gx + x, gy + y] = (0xFF, 0xFF, 0xFF)
        im.resize((im.width * 6, im.height * 6), Image.NEAREST).save(os.path.join(HERE, 'font64.png'))
    except ImportError:
        pass
    print("font64.asm written")
